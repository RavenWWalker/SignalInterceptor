namespace SignalInterceptor.AI.Psycaster
{
    /// <summary>
    /// Тактическая роль вражеской пешки с точки зрения пси-кастера.
    /// Используется в EnemyAssessment и сорсерах способностей для подбора целей.
    /// Назначается один раз при сборке BattlefieldSnapshot и не меняется в течение тика.
    /// </summary>
    public enum EnemyRole
    {
        /// <summary>
        /// Не классифицировано / неизвестная цель. По умолчанию — относиться как к Wimp.
        /// </summary>
        Unknown = 0,

        /// <summary>
        /// Гражданский / без оружия / без способности применить оружие.
        /// Самая низкая угроза, низкий приоритет для контроля, но хорошая цель для добивания.
        /// </summary>
        Wimp = 1,

        /// <summary>
        /// Ближний бой с человеком (нож, дубина, меч, кулаки).
        /// Опасность пропорциональна дистанции: вблизи — критическая, вдали — нулевая.
        /// </summary>
        Melee = 2,

        /// <summary>
        /// Дальник короткой/средней дистанции (пистолет, дробовик, автомат).
        /// Опасность стабильно высокая в радиусе ~15 клеток.
        /// </summary>
        Ranged = 3,

        /// <summary>
        /// Снайпер или дальник с дальностью 25+ клеток.
        /// Главная цель для контроля: BlindingPulse, Stun, Wallraise.
        /// Определяется по verbProps.range у основного оружия.
        /// </summary>
        Sniper = 4,

        /// <summary>
        /// Дикое или ручное животное игрока.
        /// Кандидат для ManhunterPulse. Не реагирует на Berserk (animal mind).
        /// </summary>
        Animal = 5,

        /// <summary>
        /// Механоид игрока. Иммунен к психо-способностям (Berserk/BlindingPulse/etc).
        /// Атакуется только Stun и физически. Полный игнор для большинства сорсеров.
        /// </summary>
        Mechanoid = 6,

        /// <summary>
        /// Тяжёлый дальник (пулемётчик, гранатомётчик, ракетчик, чарж-ланс).
        /// Крайне высокий приоритет контроля. Определяется по большой массе оружия
        /// или наличию взрывного/area damage у verbProps.
        /// </summary>
        Heavy = 7,

        /// <summary>
        /// Вражеский пси-кастер. Высокая угроза по способностям, низкая по урону.
        /// Стоит контролить Stun-ом, чтобы прервать его собственный каст.
        /// </summary>
        Psycaster = 8
    }
}
