namespace SignalInterceptor.AI.Psycaster
{
    /// <summary>
    /// Стратегическая «поза» пси-кастера. Выбирается раз в 240-500 тиков либо по триггеру.
    /// Поза — это не действие, а контекст: она задаёт множители для скоров способностей,
    /// чтобы AI вёл себя по-разному в разных ситуациях, не ломая логику выбора цели.
    /// </summary>
    public enum PsycasterStance
    {
        /// <summary>
        /// Бой ещё не начался либо никто не получил/нанёс урон последние ~600 тиков.
        /// Главное действие — Focus, превентивный Stun/BlindingPulse на самого опасного дальника.
        /// </summary>
        Opening = 0,

        /// <summary>
        /// Основная поза против дальнобойного противника.
        /// Цель — держать дистанцию 18-25 клеток, разрывать LOS через Wallraise/Smokepop,
        /// отрываться через Skip-self при сближении.
        /// </summary>
        Kite = 1,

        /// <summary>
        /// Против ближников. Развести через Skip (себя или врага), оглушить волной,
        /// обстрелять ChaosSkip / Berserk Pulse если их больше двух.
        /// </summary>
        Disengage = 2,

        /// <summary>
        /// 4+ враждебных пешек, подходящих для AoE.
        /// Приоритет: Berserk Pulse, Mass Chaos Skip, Vertigo Pulse, Manhunter Pulse при наличии животных.
        /// </summary>
        CrowdControl = 3,

        /// <summary>
        /// Игрок разделён, есть изолированная цель (раненая или одиночка).
        /// Самая «злая» поза: Invisibility → подход → Stun → добивание.
        /// </summary>
        Hunt = 4,

        /// <summary>
        /// Окружили со всех сторон в ближнем бою (2+ врагов в радиусе 2.2),
        /// но HP ещё нормальный. Приоритет — экстренное разведение через Mass Chaos Skip,
        /// BulletShield, Wallraise. Не отступление.
        /// </summary>
        Engulfed = 5,

        /// <summary>
        /// HP ниже критического порога (по умолчанию 35%) ИЛИ пси-кастер беспомощен
        /// (без psyfocus, без cooldown-готовых способностей в окружении).
        /// Приоритет — выживание любой ценой: BulletShield + Invisibility + Skip-self в дальний угол.
        /// </summary>
        Survive = 6
    }
}
